#!/bin/sh
# Санитизация дампа MySQL в два этапа.
#
#   Этап 1 — myanon: замена значений в структурированных колонках по конфигу.
#            Детерминированно: одно и то же значение заменяется одинаково везде.
#   Этап 2 — доработка: подстановка тех же замен внутрь свободного текста.
#            myanon заменяет поле целиком и внутрь строки не смотрит, поэтому
#            без этого этапа значение, обработанное в своей колонке, остаётся
#            открытым там, где упомянуто в тексте, и сквозная замена не выполнена.
#
# Секрет берётся из окружения и не попадает ни в репозиторий, ни в артефакты:
# временный конфиг создаётся с правами 600 и удаляется в любом случае,
# включая прерывание.
#
# Использование:
#   SANITIZE_SECRET='...' scripts/sanitize.sh input.sql output.sql

set -eu

IN="${1:?укажите входной дамп}"
OUT="${2:?укажите выходной файл}"
DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$DIR/.." && pwd)"

# Бинарь myanon берётся из PATH: в образе он ставится в /usr/local/bin.
# При локальном запуске путь к собранному бинарю задаётся через MYANON_BIN.
BIN="${MYANON_BIN:-$(command -v myanon || true)}"
TPL="${SANITIZER_CONFIG:-$ROOT/config}/myanon.conf.template"

if [ -z "${SANITIZE_SECRET:-}" ]; then
  echo "Ошибка: переменная SANITIZE_SECRET не задана." >&2
  echo "Секрет определяет результат замен: один и тот же секрет даёт одинаковые" >&2
  echo "замены при повторных прогонах, другой секрет даёт другие." >&2
  exit 1
fi

[ -n "$BIN" ] && [ -x "$BIN" ] || {
  echo "Ошибка: не найден бинарь myanon. Соберите его и укажите MYANON_BIN." >&2; exit 1; }
[ -f "$TPL" ] || { echo "Ошибка: не найден шаблон $TPL" >&2; exit 1; }

# Пакет ищется в src/, если он не установлен (локальный запуск без pip install).
[ -d "$ROOT/src" ] && PYTHONPATH="$ROOT/src${PYTHONPATH:+:$PYTHONPATH}" && export PYTHONPATH

# Старый результат удаляется до начала: если прогон упадёт, проверять
# будет нечего, и отчёт не сможет показать успех на устаревшем файле.
rm -f "$OUT"

CONF="$(mktemp "${TMPDIR:-/tmp}/myanon.XXXXXX.conf")"
STAGE1="$(mktemp "${TMPDIR:-/tmp}/stage1.XXXXXX.sql")"
chmod 600 "$CONF"
trap 'rm -f "$CONF" "$STAGE1"' EXIT INT TERM

# Разделитель | вместо / — секрет может содержать слеши.
sed "s|__SECRET__|$SANITIZE_SECRET|" "$TPL" > "$CONF"

echo "Этап 1: структурированные колонки"
"$BIN" -f "$CONF" < "$IN" > "$STAGE1"
grep '^-- TOTAL' "$STAGE1" || true

echo "Этап 2: свободный текст"
python3 -m sanitizer.text_substitute "$IN" "$STAGE1" "$OUT"
