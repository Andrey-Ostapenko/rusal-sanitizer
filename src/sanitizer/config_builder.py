#!/usr/bin/env python3
"""
Сборка конфига myanon из находок сканера — шаг 2 цикла автонастройки.

Модель отдаёт типизированный список находок, конфиг собирает этот модуль.
Вывод модели не становится исполняемым.

Два правила цикла:

  1. Внутри цикла правила ТОЛЬКО добавляются. Существующее правило не
     заменяется и не удаляется, иначе покрытие может молча упасть.
  2. Вид находки проверяется по белому списку `ВИДЫ` из `scan_columns`.
     Это граница доверия: находки приходят от модели, и вид, которого нет
     в списке, в конфиг не попадёт, что бы она ни ответила.

Использование:
    python3 -m sanitizer.config_builder scan_report.json [дамп] [конфиг] [выход]
    python3 -m sanitizer.config_builder --самопроверка
"""
import json
import re
import sys

from . import paths
from .scan_columns import ВИДЫ
from .sql_parse import parse_inserts, unquote

# Ограничение инструмента: main/myanon.h:69, MAX_LEN = 32.
# Для emailhash должно выполняться N + длина_домена + 1 <= MAX_LEN.
MAX_LEN = 32
ДЛИНА_ТЕКСТА = 30
ДЛИНА_ПОЧТЫ = 10

# RFC 2606 резервирует .invalid — такой домен заведомо никому не принадлежит.
ДОМЕН_ПО_УМОЛЧАНИЮ = "example.invalid"

_БЛОК = re.compile(r"`(\w+)`\s*=\s*\{(.*?)\}", re.S)
_ПРАВИЛО = re.compile(r"`(\w+)`\s*=\s*(\S[^\n]*?)\s*$", re.M)


def разобрать(текст):
    """Текст конфига -> (шапка до tables, {(таблица, колонка): правило})."""
    i = текст.find("tables")
    if i < 0:
        return текст.rstrip() + "\n", {}
    шапка = текст[:i]
    тело = текст[текст.index("{", i) + 1: текст.rindex("}")]
    правила = {}
    for m in _БЛОК.finditer(тело):
        таблица, блок = m.group(1), m.group(2)
        for r in _ПРАВИЛО.finditer(блок):
            правила[(таблица, r.group(1))] = r.group(2)
    return шапка, правила


def собрать(шапка, правила):
    """{(таблица, колонка): правило} -> текст конфига."""
    по_таблицам = {}
    for (таблица, колонка), правило in правила.items():
        по_таблицам.setdefault(таблица, {})[колонка] = правило

    куски = [шапка.rstrip("\n"), "", "tables = {"]
    for таблица in sorted(по_таблицам):
        куски.append(f"  `{таблица}` = {{")
        ширина = max(len(c) for c in по_таблицам[таблица]) + 2
        for колонка in sorted(по_таблицам[таблица]):
            имя = f"`{колонка}`".ljust(ширина)
            куски.append(f"    {имя} = {по_таблицам[таблица][колонка]}")
        куски.append("  }")
        куски.append("")
    if куски[-1] == "":
        куски.pop()
    куски.append("}")
    return "\n".join(куски) + "\n"


def домен(данные, таблица, колонка):
    """Домен из реальных значений колонки; иначе заведомо несуществующий."""
    если_нет = ДОМЕН_ПО_УМОЛЧАНИЮ
    if таблица not in данные:
        return если_нет
    колонки, строки = данные[таблица]
    if колонка not in колонки:
        return если_нет
    idx = колонки.index(колонка)
    for строка in строки:
        значение = unquote(строка[idx])
        if "@" in значение:
            return значение.rsplit("@", 1)[1]
    return если_нет


def правило_для(вид, данные, таблица, колонка):
    """Находка -> строка правила myanon, либо (None, причина отказа)."""
    действие = ВИДЫ.get(вид)
    if действие is None:
        return None, f"вид «{вид}» не в белом списке"
    if действие == "texthash":
        return f"texthash {ДЛИНА_ТЕКСТА}", None
    if действие == "emailhash":
        d = домен(данные, таблица, колонка)
        n = min(ДЛИНА_ПОЧТЫ, MAX_LEN - len(d) - 1)
        if n < 1:
            return None, (f"домен «{d}» длиной {len(d)} не оставляет места "
                          f"под хеш при MAX_LEN={MAX_LEN}")
        return f"emailhash '{d}' {n}", None
    return None, f"действие «{действие}» не поддержано сборщиком"


def добавить(правила, находки, данные):
    """Добавляет находки к правилам. Возвращает (новые правила, отчёт)."""
    правила = dict(правила)
    добавлено, пропущено = [], []
    for f in находки:
        ключ = (f["таблица"], f["колонка"])
        if ключ in правила:
            пропущено.append((*ключ, "правило уже есть, замена запрещена"))
            continue
        правило, причина = правило_для(f["вид"], данные, *ключ)
        if правило is None:
            пропущено.append((*ключ, причина))
            continue
        правила[ключ] = правило
        добавлено.append((*ключ, правило))
    return правила, {"добавлено": добавлено, "пропущено": пропущено}


def main(отчёт_сканера, дамп=None, конфиг=None, выход=None):
    дамп = дамп or paths.данные("demo_dump.sql")
    конфиг = конфиг or str(paths.CONFIG / "myanon.conf.template")
    выход = выход or конфиг

    находки = json.load(open(отчёт_сканера, encoding="utf-8"))["находки"]
    if not находки:
        # Сломанный сканер и чистая база дают один сигнал: пустой результат
        # не может считаться успехом.
        print("ОТКАЗ: в отчёте сканера нет ни одной находки, собирать нечего.")
        return 1

    шапка, было = разобрать(open(конфиг, encoding="utf-8").read())
    стало, отчёт = добавить(было, находки, parse_inserts(дамп))

    for т, к, правило in отчёт["добавлено"]:
        print(f"  + {т}.{к} = {правило}")
    for т, к, почему in отчёт["пропущено"]:
        print(f"  · {т}.{к}: {почему}")
    print(f"\nПравил было {len(было)}, стало {len(стало)}.")

    if стало == было:
        print("Конфиг не изменился.")
        return 0

    open(выход, "w", encoding="utf-8").write(собрать(шапка, стало))
    print(f"Записан {выход}. Дифф смотрит человек — правила добавлены, "
          "ни одно не удалено.")
    return 0


def _самопроверка():
    исходный = """secret = '__SECRET__'
stats  = 'yes'

tables = {
  `customers` = {
    `email`     = emailhash 'example-mail.ru' 10
    `address`   = texthash 30
  }
}
"""
    шапка, правила = разобрать(исходный)
    assert правила == {
        ("customers", "email"): "emailhash 'example-mail.ru' 10",
        ("customers", "address"): "texthash 30",
    }, правила
    assert "secret" in шапка and "tables" not in шапка

    # Круговой обход: собранное разбирается в тот же набор правил.
    assert разобрать(собрать(шапка, правила))[1] == правила

    данные = {"customers": (["id", "email", "full_name"],
                            [["1", "'i@demo-mail.ru'", "'Иванова Ольга'"]])}
    находки = [
        {"таблица": "customers", "колонка": "full_name", "вид": "имя"},
        {"таблица": "customers", "колонка": "address", "вид": "адрес"},
        {"таблица": "customers", "колонка": "email", "вид": "почта"},
        {"таблица": "customers", "колонка": "id", "вид": "паспорт"},
    ]
    стало, отчёт = добавить(правила, находки, данные)

    assert стало[("customers", "full_name")] == f"texthash {ДЛИНА_ТЕКСТА}", стало
    # Существующее правило не тронуто, хотя находка на эту колонку была.
    assert стало[("customers", "address")] == "texthash 30", стало
    assert стало[("customers", "email")] == "emailhash 'example-mail.ru' 10"
    # Вид вне белого списка в конфиг не попал.
    assert ("customers", "id") not in стало, стало
    причины = {к: п for _, к, п in отчёт["пропущено"]}
    assert "белом списке" in причины["id"], причины
    assert "замена запрещена" in причины["address"], причины

    # Домен берётся из данных, длина укладывается в ограничение инструмента.
    правило, причина = правило_для("почта", данные, "customers", "email")
    assert правило == "emailhash 'demo-mail.ru' 10", правило
    assert причина is None
    # Нет данных — заведомо несуществующий домен, а не угадывание.
    assert правило_для("почта", {}, "x", "y")[0] == \
        f"emailhash '{ДОМЕН_ПО_УМОЛЧАНИЮ}' {ДЛИНА_ПОЧТЫ}"
    # Длинный домен: N ужимается, а если места нет — отказ с причиной.
    длинный = {"t": (["e"], [["'a@" + "d" * 40 + ".ru'"]])}
    правило, причина = правило_для("почта", длинный, "t", "e")
    assert правило is None and "MAX_LEN" in причина, (правило, причина)

    print("config_builder: самопроверка пройдена")
    return 0


if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "--самопроверка":
        sys.exit(_самопроверка())
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    sys.exit(main(*sys.argv[1:5]))
