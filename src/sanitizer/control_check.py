#!/usr/bin/env python3
"""
Проверка самого контрольного набора и замер детерминированного слоя на нём.

Зачем отдельный файл: контрольный набор — эталон, по которому будет судиться
детектор и стартовать цикл автонастройки. Неверный эталон даёт неверный
приговор молча, поэтому эталон проверяется до всякого его применения
(красный флаг 2.2 — не проверять сам инструмент проверки).

Что проверяется:
  1. Разметка внутренне согласована: каждое размеченное значение реально
     встречается в своём тексте.
  2. Контрольные суммы размеченных ИНН и СНИЛС верны, а у отрицательных
     примеров, объявленных «сумма неверна», — неверны. Реализация сумм здесь
     написана заново и не импортируется из pii_patterns.py: иначе ошибка
     нашего кода перешла бы в эталон и стала бы неотличима от истины.
  3. Значения набора не встречаются в демо-дампе — замер независим от данных,
     на которых решение отлаживалось.
  4. Базовый замер: что на этом наборе берёт нынешний детерминированный слой
     без всякой модели. Это точка отсчёта, с которой сравнивается детектор.

Использование:
    python3 control_check.py [control_set.json] [demo_dump.sql]
"""
from . import paths
import json
import os
import sys

W1 = [7, 2, 4, 10, 3, 5, 9, 4, 6, 8]
W2 = [3, 7, 2, 4, 10, 3, 5, 9, 4, 6, 8]


def inn12_ok(s):
    """Независимая реализация: два контрольных разряда 12-значного ИНН."""
    if len(s) != 12 or not s.isdigit():
        return False
    d = [int(c) for c in s]
    c11 = sum(w * x for w, x in zip(W1, d[:10])) % 11 % 10
    c12 = sum(w * x for w, x in zip(W2, d[:11])) % 11 % 10
    return d[10] == c11 and d[11] == c12


def snils_ok(s):
    """Независимая реализация: контрольное число СНИЛС."""
    digits = [c for c in s if c.isdigit()]
    if len(digits) != 11:
        return False
    d = [int(c) for c in digits]
    total = sum((9 - i) * d[i] for i in range(9))
    check = int(f"{d[9]}{d[10]}")
    if total < 100:
        return check == total
    if total in (100, 101):
        return check == 0
    total %= 101
    return check == (0 if total in (100, 101) else total)


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def check_markup(records):
    """Каждое размеченное значение должно встречаться в своём тексте."""
    bad = []
    for r in records:
        for p in r.get("пдн", []):
            if p["значение"] not in r["текст"]:
                bad.append((r["id"], p["значение"]))
    return bad


def check_sums(records):
    """Суммы у положительных верны; у отрицательных, заявленных неверными, — неверны."""
    bad = []
    checked = 0
    for r in records:
        for p in r.get("пдн", []):
            if p["вид"] == "инн":
                checked += 1
                if not inn12_ok(p["значение"]):
                    bad.append((r["id"], p["значение"], "ИНН размечен, но сумма неверна"))
            elif p["вид"] == "снилс":
                checked += 1
                if not snils_ok(p["значение"]):
                    bad.append((r["id"], p["значение"], "СНИЛС размечен, но сумма неверна"))
        why = r.get("почему_сложный", "")
        if "сумма неверна" in why:
            # Счётчик увеличивается только когда действительно нашлось, что
            # сверять. Иначе объявленная проверка засчитывалась бы выполненной,
            # не проверив ничего (красный флаг 2.17 внутри самого инструмента).
            import re
            нашлось = False
            for t in (w.strip(".,:;") for w in r["текст"].split()):
                if t.isdigit() and len(t) == 12:
                    нашлось = True
                    checked += 1
                    if inn12_ok(t):
                        bad.append((r["id"], t, "заявлен неверным, но сумма верна"))
            for m in re.finditer(r"\d{3}-\d{3}-\d{3}\s\d{2}", r["текст"]):
                нашлось = True
                checked += 1
                if snils_ok(m.group(0)):
                    bad.append((r["id"], m.group(0), "заявлен неверным, но сумма верна"))
            if not нашлось:
                bad.append((r["id"], "", "заявлено «сумма неверна», но числа для сверки нет"))
    return bad, checked


def check_ids(records):
    """Повторяющийся идентификатор молча склеит записи при любом сопоставлении."""
    seen, dup = set(), []
    for r in records:
        if r["id"] in seen:
            dup.append(r["id"])
        seen.add(r["id"])
    return dup


def check_texts_original(records, dump_path, window=5):
    """
    Ни один текст набора не должен быть копией текста из демо-данных.

    Совпадения отдельных общих слов («заказ», «клиент») неизбежны и ничего не
    значат. Значимо совпадение подряд идущего окна слов: это признак, что
    запись списана с шаблона генератора, то есть эталон проверяет решение
    данными самого решения (красный флаг 2.1).
    """
    if not os.path.exists(dump_path):
        return None
    dump = open(dump_path, encoding="utf-8").read()
    hits = []
    for r in records:
        words = r["текст"].split()
        for i in range(len(words) - window + 1):
            frag = " ".join(words[i:i + window])
            if frag in dump:
                hits.append((r["id"], frag))
                break
    return hits


def check_independence(records, dump_path):
    """Ни одно значение набора не должно встречаться в демо-данных."""
    if not os.path.exists(dump_path):
        return None
    text = open(dump_path, encoding="utf-8").read()
    hit = []
    for r in records:
        for p in r.get("пдн", []):
            if p["значение"] in text:
                hit.append((r["id"], p["значение"]))
    return hit


ОБЩИЙ_ПРЕФИКС = 5


def _слова(s):
    return [w.strip(".,:;!?«»\"'()").lower() for w in s.split() if w.strip(".,:;«»\"'()")]


def совпадают(найдено, размечено, вид):
    """
    Одно правило сравнения найденного с эталоном — на весь проект.

    Отдельная функция, потому что сравнение по строке целиком уже дважды
    давало ложный ноль (красный флаг 2.2): модель возвращает «Сергей Малахов»,
    а в тексте стоит «Сергею Малахову», и посимвольное равенство объявляет
    промах там, где детектор сработал верно.

    Для строгих форматов сравнение точное: телефон и ИНН либо тот, либо не тот.
    Для имён достаточно, чтобы у какого-то слова находки и какого-то слова
    эталона совпал начальный кусок длиной ОБЩИЙ_ПРЕФИКС — это снимает
    падежные окончания, не сливая разные фамилии.
    """
    if вид != "имя":
        return найдено.strip() == размечено.strip()
    for a in _слова(найдено):
        for b in _слова(размечено):
            n = min(len(a), len(b), ОБЩИЙ_ПРЕФИКС)
            if n >= ОБЩИЙ_ПРЕФИКС and a[:n] == b[:n]:
                return True
    return False


def _проверить_правило_сравнения():
    """Само правило сравнения тоже инструмент проверки — его проверяем первым."""
    должны = [
        ("Сергей Малахов", "Сергею Малахову"),
        ("Гаврилин", "гаврилиным"),
        ("Вера Ануфриева", "Веры Ануфриевой"),
        ("Мазурова", "инспектор Мазурова"),
    ]
    не_должны = [
        ("Иванов Пётр", "Сидоров Павел"),
        ("Малахов", "Мазурова"),
        ("Ольга", "Олег"),
    ]
    сбои = []
    for a, b in должны:
        if not совпадают(a, b, "имя"):
            сбои.append(("не совпало, а должно", a, b))
    for a, b in не_должны:
        if совпадают(a, b, "имя"):
            сбои.append(("совпало, а не должно", a, b))
    if совпадают("+79161234567", "+7 916 123-45-67", "телефон"):
        сбои.append(("формат сравнён нестрого", "", ""))
    return сбои


# Соответствие видов: в наборе они по-русски, в pii_patterns — по-английски.
ВИД_ПО_ИМЕНИ = {"snils": "снилс", "phone": "телефон", "email": "почта", "inn12": "инн"}
ФОРМАТНЫЕ = {"снилс", "телефон", "почта", "инн"}


def baseline(records):
    """
    Что берёт нынешний детерминированный слой без модели.

    Считается отдельно по форматным видам и по именам. Имена он не берёт
    по устройству — это и есть та дыра, ради которой нужен детектор, и
    показать её числом честнее, чем словами.
    """
    from . import pii_patterns

    формат_всего = формат_найдено = 0
    имён_всего = имён_найдено = 0
    ложных = []

    for r in records:
        найдено = pii_patterns.find_values(r["текст"])
        размечено = {p["значение"]: p["вид"] for p in r.get("пдн", [])}

        for знач, вид in размечено.items():
            попал = any(совпадают(f, знач, вид) and ВИД_ПО_ИМЕНИ.get(t) == вид
                        for f, t in найдено.items())
            if вид in ФОРМАТНЫЕ:
                формат_всего += 1
                формат_найдено += попал
            else:
                имён_всего += 1
                имён_найдено += попал

        for f, t in найдено.items():
            вид_f = ВИД_ПО_ИМЕНИ.get(t, t)
            if not any(совпадают(f, знач, вид) for знач, вид in размечено.items()):
                ложных.append((r["id"], f, вид_f))

    return {
        "формат_всего": формат_всего, "формат_найдено": формат_найдено,
        "имён_всего": имён_всего, "имён_найдено": имён_найдено,
        "ложных": ложных,
    }


def main(set_path, dump_path):
    данные = load(set_path)
    записи = данные["записи"]
    положительных = sum(1 for r in записи if r.get("пдн"))
    отрицательных = len(записи) - положительных
    провалено = 0

    print(f"\nЗаписей в наборе: {len(записи)} "
          f"(с ПДн: {положительных}, без ПДн: {отрицательных})")

    if not записи:
        print("ОТКАЗ: набор пуст, проверять нечего.")
        return 1

    сбои_правила = _проверить_правило_сравнения()
    print(f"Правило сравнения с эталоном             : "
          f"{'норма' if not сбои_правила else 'НАРУШЕНО ' + str(сбои_правила[:3])}")
    провалено += bool(сбои_правила)

    дубли = check_ids(записи)
    print(f"Идентификаторы уникальны                 : "
          f"{'норма' if not дубли else 'НАРУШЕНО ' + str(дубли)}")
    провалено += bool(дубли)

    плохая = check_markup(записи)
    print(f"Разметка согласована с текстами          : "
          f"{'норма' if not плохая else 'НАРУШЕНО ' + str(плохая[:3])}")
    провалено += bool(плохая)

    плохие_суммы, сверено = check_sums(записи)
    ok = сверено > 0 and not плохие_суммы
    print(f"Контрольные суммы ИНН и СНИЛС            : "
          f"{'норма' if ok else 'НАРУШЕНО ' + str(плохие_суммы[:3])} "
          f"(сверено {сверено})")
    провалено += not ok

    пересечение = check_independence(записи, dump_path)
    if пересечение is None:
        print(f"Независимость от демо-данных             : ПРОПУЩЕНО ({dump_path} не найден)")
        провалено += 1
    else:
        print(f"Значения не встречаются в демо-данных    : "
              f"{'норма' if not пересечение else 'НАРУШЕНО ' + str(пересечение[:3])}")
        провалено += bool(пересечение)

    списано = check_texts_original(записи, dump_path)
    if списано is None:
        print(f"Тексты не списаны с демо-данных          : ПРОПУЩЕНО ({dump_path} не найден)")
        провалено += 1
    else:
        print(f"Тексты не списаны с демо-данных          : "
              f"{'норма' if not списано else 'НАРУШЕНО ' + str(списано[:3])}")
        провалено += bool(списано)

    b = baseline(записи)
    print(f"\nБазовый замер без модели:")
    print(f"  строгий формат  : найдено {b['формат_найдено']} из {b['формат_всего']}")
    print(f"  имена в тексте  : найдено {b['имён_найдено']} из {b['имён_всего']}"
          f"  <- дыра, ради которой нужен детектор")
    print(f"  ложных срабатываний: {len(b['ложных'])}"
          + (f" {b['ложных'][:3]}" if b["ложных"] else ""))
    if b["имён_всего"]:
        print(f"\n  Гранулярность замера по именам: один промах = "
              f"{1 / b['имён_всего']:.2f} полноты ({b['имён_всего']} примеров). "
              f"Точность выше этого шага набор не даёт.")

    # Пустой замер — это отказ, а не успех (красный флаг 2.17). Без этой
    # проверки набор без форматных ПДн дал бы «0 из 0» и прошёл бы молча.
    if b["формат_всего"] == 0 or b["имён_всего"] == 0:
        print("ОТКАЗ: в наборе нет примеров одного из видов — замер вхолостую.")
        провалено += 1
    elif b["формат_найдено"] < b["формат_всего"] or b["ложных"]:
        провалено += 1

    print()
    if провалено:
        print(f"Провалено проверок: {провалено}")
        return 1
    print("Эталон пригоден: разметка верна, суммы сходятся, "
          "пересечений с демо-данными нет.")
    return 0


if __name__ == "__main__":
    s = sys.argv[1] if len(sys.argv) > 1 else paths.данные("control_set.json")
    d = sys.argv[2] if len(sys.argv) > 2 else paths.данные("demo_dump.sql")
    sys.exit(main(s, d))
