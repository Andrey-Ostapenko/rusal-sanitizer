#!/usr/bin/env python3
"""
Детектор персональных данных в свободном тексте.

Роль модели в решении — НАХОДИТЬ, а не порождать замены. Порождение отвергнуто
замером: при независимых вызовах модель тяготеет к частотным значениям и
схлопывает разнообразие (`claude/poc_run_4_model.md`). Найденное заменяет
детерминированный механизм, у которого разнообразие гарантировано построением.

Детектор ищет ТОЛЬКО имена людей. Обоснование, а не экономия:
телефон, ИНН, СНИЛС и почту уже берёт `pii_patterns` по формату с проверкой
контрольных сумм — там полнота и точность доказуемы арифметикой, и подключать
к ним модель значит менять доказуемое на вероятное. Имя в свободном тексте —
единственный вид ПДн, у которого нет ни формата, ни источника в колонках;
это и есть та дыра, которую детерминированный слой не закрывает (замерено:
`control_check.py` показывает 0 из 10).

Замер — `python3 -m sanitizer.detect measure`. Результат кладётся
в detect_report.json.
"""
from . import paths
import json
import os
import re
import sys
import time
import urllib.request

ENDPOINT = os.environ.get("LLM_ENDPOINT", "http://localhost:12434/engines/v1/chat/completions")
MODEL = os.environ.get("LLM_MODEL", "ai/qwen3:14b-q4_K_M")

ПРОМПТ = """/no_think Ты ищешь имена людей в тексте комментария из базы данных.

Верни JSON-массив строк — фрагменты текста, которые называют конкретного человека
(фамилия, имя, отчество, инициалы, в любом падеже, как они написаны в тексте).

Не считай именем человека:
- название организации, даже если оно образовано от фамилии;
- название улицы, завода, площади, образованное от фамилии;
- обычное слово, совпадающее с именем («надежда», «вера», «мороз», «роман»).

Если людей в тексте нет, верни пустой массив [].
Ответь только JSON-массивом, без пояснений.

Текст: {текст}"""


def _вызов(prompt, timeout=180):
    body = json.dumps({
        "model": MODEL,
        "messages": [{"role": "user", "content": prompt}],
        "temperature": 0,        # поиск должен быть воспроизводим, а не разнообразен
        "max_tokens": 400,
    }).encode()
    req = urllib.request.Request(ENDPOINT, data=body,
                                 headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        data = json.loads(r.read())
    text = data["choices"][0]["message"]["content"]
    return re.sub(r"<think>.*?</think>", "", text, flags=re.S).strip()


def detect(текст):
    """Возвращает список находок [{'значение': ..., 'вид': 'имя'}]."""
    сырое = _вызов(ПРОМПТ.format(текст=текст))
    m = re.search(r"\[.*\]", сырое, re.S)
    if not m:
        raise ValueError(f"модель вернула не JSON: {сырое[:200]}")
    массив = json.loads(m.group(0))
    находки = []
    for x in массив:
        if isinstance(x, str) and x.strip():
            находки.append({"значение": x.strip(), "вид": "имя"})
        elif isinstance(x, dict):
            # модель иногда раскладывает ФИО по полям — уже наступали на это
            склейка = " ".join(str(v) for v in x.values() if isinstance(v, str))
            if склейка.strip():
                находки.append({"значение": склейка.strip(), "вид": "имя"})
    return находки


def measure(set_path=None, out="detect_report.json"):
    """
    Полнота и точность детектора на контрольном наборе.

    Сравнение идёт правилом из control_check.совпадают — тем же самым, что
    проверено на заведомо испорченных вариантах. Отдельное сравнение здесь
    было бы четвёртым местом, где эту ошибку можно повторить.
    """
    set_path = set_path or paths.данные("control_set.json")
    from . import control_check as cc
    from . import loop_guard
    from . import pii_patterns

    сырых = отброшено_вложенных = 0

    сбои = cc._проверить_правило_сравнения()
    if сбои:
        print(f"ОТКАЗ: правило сравнения неисправно: {сбои[:3]}", file=sys.stderr)
        return 1

    записи = cc.load(set_path)["записи"]
    имён_всего = sum(1 for r in записи for p in r.get("пдн", []) if p["вид"] == "имя")
    if имён_всего == 0:
        print("ОТКАЗ: в наборе нет имён — мерить нечего.", file=sys.stderr)
        return 1

    найдено_верно = 0
    ложных = []
    пропущено = []
    подробно = []
    t0 = time.time()

    for i, r in enumerate(записи, 1):
        эталон = [p["значение"] for p in r.get("пдн", []) if p["вид"] == "имя"]
        try:
            находки = detect(r["текст"])
        except Exception as e:                      # noqa: BLE001
            print(f"  {r['id']}: ОШИБКА {e}", file=sys.stderr)
            находки = None
        if находки is None:
            подробно.append({"id": r["id"], "ошибка": True})
            continue

        # Находки, лежащие внутри значения, которое уже покрыто форматным
        # слоем, отбрасываются. Фильтр нужен сам по себе, независимо от того,
        # как он влияет на числа: отдельное правило на кусок уже заменяемого
        # значения защиты не добавляет, а вторую замену внутри одного
        # значения создаёт. Сырое число тоже публикуется — ниже.
        покрытые = set(pii_patterns.find_values(r["текст"]))
        сырых += len(находки)
        находки, вложенные = loop_guard.убрать_вложенные(находки, покрытые)
        отброшено_вложенных += len(вложенные)

        попали = set()
        for f in находки:
            совпал = next((э for э in эталон if cc.совпадают(f["значение"], э, "имя")), None)
            if совпал:
                попали.add(совпал)
            else:
                ложных.append({"id": r["id"], "нашёл": f["значение"], "текст": r["текст"]})
        найдено_верно += len(попали)
        for э in эталон:
            if э not in попали:
                пропущено.append({"id": r["id"], "пропустил": э, "текст": r["текст"]})

        подробно.append({"id": r["id"], "эталон": эталон,
                         "находки": [f["значение"] for f in находки]})
        print(f"  {i}/{len(записи)} {r['id']}: эталон {len(эталон)}, "
              f"найдено {len(находки)}", flush=True)

    ошибок = sum(1 for d in подробно if d.get("ошибка"))
    полнота = найдено_верно / имён_всего
    всего_находок = найдено_верно + len(ложных)
    точность = найдено_верно / всего_находок if всего_находок else 0.0

    отчёт = {
        "модель": MODEL,
        "записей": len(записи), "имён_в_эталоне": имён_всего,
        "найдено_верно": найдено_верно, "пропущено": len(пропущено),
        "ложных": len(ложных), "ошибок_вызова": ошибок,
        "полнота": round(полнота, 3), "точность": round(точность, 3),
        "находок_сырых": сырых, "отброшено_вложенных": отброшено_вложенных,
        "точность_без_фильтра": round(
            найдено_верно / (найдено_верно + len(ложных) + отброшено_вложенных), 3)
        if (найдено_верно + len(ложных) + отброшено_вложенных) else 0.0,
        "секунд": round(time.time() - t0, 1),
        "подробно_пропущено": пропущено, "подробно_ложных": ложных,
        "подробно": подробно,
    }
    with open(out, "w", encoding="utf-8") as f:
        json.dump(отчёт, f, ensure_ascii=False, indent=1)

    print()
    if ошибок:
        print(f"ОТКАЗ: {ошибок} вызовов модели не удались — замер неполон.")
    print(f"Имён в эталоне : {имён_всего}")
    print(f"Найдено верно  : {найдено_верно}")
    print(f"Пропущено      : {len(пропущено)}")
    print(f"Ложных         : {len(ложных)}")
    print(f"Полнота        : {полнота:.2f}")
    print(f"Точность       : {точность:.2f}"
          f"  (без фильтра вложенных: {отчёт['точность_без_фильтра']:.2f}, "
          f"отброшено вложенных {отброшено_вложенных} из {сырых} находок)")
    print(f"Время          : {отчёт['секунд']} с на {len(записи)} записей")
    print(f"Отчёт          : {out}")

    from . import loop_guard
    можно, причина = loop_guard.старт_разрешён(полнота, точность, set_path)
    print(f"\nСтарт цикла    : {'разрешён' if можно else 'ЗАПРЕЩЁН'} — {причина}")
    return 0 if (можно and not ошибок) else 1


if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "measure":
        sys.exit(measure())
    print(detect(sys.argv[1] if len(sys.argv) > 1
                 else "Передал курьеру Сергею Малахову, ООО «Ковалёв и партнёры» в копии."))
