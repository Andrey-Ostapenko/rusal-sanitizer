#!/usr/bin/env python3
"""
Предохранители цикла автонастройки. Модели здесь нет — только детерминированный код.

Цикл устроен так: санитизация -> детектор смотрит на результат -> находки
превращаются в правила -> санитизация заново. У такого цикла два способа
испортиться молча, и оба закрываются здесь.

1. Цикл гоняется за собственными заменами. Детектор смотрит на результат, а в
   результате стоят замены; замену он тоже может опознать как ПДн и потребовать
   правило. Отсюда `actionable`: находка засчитывается, только если фрагмент
   встречается во ВХОДНОМ дампе. Это следует из определения — значения, которого
   во входе нет, во входных данных не утекло.

   Границы: фильтр верен, пока конвейер только заменяет значения. Если появится
   обратимое кодирование, где выходное значение является преобразованием
   входного, фильтр начнёт пропускать утечки и его придётся пересматривать.

2. Цикл не сходится. Отсюда потолок итераций: не сошлось за N — падаем с
   отчётом, а не крутимся.

Отдельно: старт цикла разрешает `control_check.py` — детектор обязан показать
заданную полноту на контрольном наборе. Сломанный детектор и чистые данные
дают один и тот же сигнал «ничего не найдено», и без внешнего эталона
остановка цикла не означает ничего.
"""
from . import paths
import json
import sys

def actionable(находки, исходный_текст):
    """
    Оставляет только те находки, чьё значение есть во входном дампе.

    находки: список словарей с ключом «значение».
    Возвращает (принятые, отброшенные).
    """
    принятые, отброшенные = [], []
    for f in находки:
        (принятые if f["значение"] in исходный_текст else отброшенные).append(f)
    return принятые, отброшенные


def убрать_вложенные(находки, покрытые):
    """
    Отбрасывает находки, целиком лежащие внутри уже покрытого значения.

    Замерено: в тексте «...на v.pankratov@partner-logistic.ru, он ведёт
    договор» детектор отдельно называет «v.pankratov» — и он не ошибается,
    это действительно фамилия. Но адрес почты уже заменяется целиком по
    формату, и отдельное правило на его кусок не добавляет защиты, зато
    создаёт вторую замену внутри одного значения.

    Фильтр детерминированный: сравнение подстрок, модель не участвует.
    Возвращает (принятые, отброшенные).
    """
    принятые, отброшенные = [], []
    for f in находки:
        v = f["значение"]
        если_внутри = any(v != c and v in c for c in покрытые)
        (отброшенные if если_внутри else принятые).append(f)
    return принятые, отброшенные


def пороги(path=None):
    """
    Порог ЖИВОСТИ детектора, ниже которого цикл не стартует.

    Это не планка качества. Он отвечает на вопрос «детектор вообще работает
    или отвалился», поэтому и стоит низко. Планка качества здесь была бы
    вредна в обе стороны: она остановила бы цикл из-за посредственного, но
    исправного детектора, а будучи выданной за качество — скрыла бы
    посредственность. Качество не пороговое, оно публикуется числом.
    """
    path = path or paths.данные("control_set.json")
    with open(path, encoding="utf-8") as f:
        p = json.load(f)["_порог_живости"]
    return p["полнота"], p["точность"]


def старт_разрешён(полнота, точность, path=None):
    """
    Разрешение на запуск цикла. Возвращает (можно, причина).

    Замер, в котором нечего было мерить, разрешением не является:
    полнота None означает, что эталон не прогонялся.
    """
    path = path or paths.данные("control_set.json")
    if полнота is None or точность is None:
        return False, "детектор не прогонялся по контрольному набору"
    п, т = пороги(path)
    if полнота < п:
        return False, f"полнота {полнота:.2f} ниже порога {п}"
    if точность < т:
        return False, f"точность {точность:.2f} ниже порога {т}"
    return True, "порог пройден"


def _самопроверка():
    """Проверка самих предохранителей — они и есть то, на что полагается цикл."""
    исход = "Клиент Иванова Ольга, ИНН 416517286227, заказ на складе."
    находки = [
        {"значение": "Иванова Ольга", "вид": "имя"},        # есть во входе
        {"значение": "416517286227", "вид": "инн"},         # есть во входе
        {"значение": "Ковалева Екатерина", "вид": "имя"},   # это замена, во входе нет
    ]
    прин, отбр = actionable(находки, исход)
    assert [f["значение"] for f in прин] == ["Иванова Ольга", "416517286227"], прин
    assert [f["значение"] for f in отбр] == ["Ковалева Екатерина"], отбр

    assert actionable([], исход) == ([], []), "пустой список не должен падать"

    покрытые = {"v.pankratov@partner-logistic.ru"}
    вн = [{"значение": "v.pankratov", "вид": "имя"},
          {"значение": "v.pankratov@partner-logistic.ru", "вид": "почта"},
          {"значение": "Малахов", "вид": "имя"}]
    п2, о2 = убрать_вложенные(вн, покрытые)
    assert [f["значение"] for f in о2] == ["v.pankratov"], о2
    assert len(п2) == 2, "само покрытое значение и посторонняя находка остаются"
    assert убрать_вложенные([], покрытые) == ([], []), "пустой список не должен падать"

    можно, _ = старт_разрешён(None, None)
    assert not можно, "непрогнанный эталон не может разрешать старт"
    п, т = пороги()
    можно, причина = старт_разрешён(п - 0.01, 1.0)
    assert not можно and "полнота" in причина, причина
    можно, причина = старт_разрешён(1.0, т - 0.01)
    assert not можно and "точность" in причина, причина
    можно, _ = старт_разрешён(п, т)
    assert можно, "ровно на пороге старт должен разрешаться"
    можно, _ = старт_разрешён(0.0, 0.0)
    assert not можно, "детектор, не нашедший ничего, старт разрешать не может"

    print("Предохранители:")
    print(f"  фильтр по входу      : принято {len(прин)}, отброшено {len(отбр)} "
          f"(отброшено как собственная замена: {отбр[0]['значение']})")
    п, т = пороги()
    print(f"  порог старта цикла   : полнота {п}, точность {т}")
    print("  самопроверка пройдена")


if __name__ == "__main__":
    sys.exit(_самопроверка())
