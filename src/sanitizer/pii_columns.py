"""
Перечень колонок, объявленных персональными. Общие данные, а не код.

Вынесено в отдельный модуль ради развязки: раньше этот перечень жил в
`text_substitute`, и `checks.verify` импортировал его оттуда же, откуда брал
функцию построения карты замен. Проверяющий был частично построен на коде
того, что проверяет: ошибка в построении карты стала бы для проверки
невидимой, потому что проверка пользовалась той же картой.

Здесь лежат только данные. От этого модуля зависят оба, друг от друга — нет.

Почему перечень не выводится из конфига myanon: конфиг описывает, что
обрабатывает myanon, а телефон, ИНН и СНИЛС обрабатывает форматный слой —
правил на них в конфиге нет и быть не должно. Перечень шире конфига намеренно.
"""

# Два перечня, а не один: у них разный смысл, и на чужой схеме разница
# становится видна.
#
# СВОБОДНЫЙ ТЕКСТ — колонки, которые осматривает детектор имён. Правило myanon
# им не назначается: оно применяется к значению целиком, то есть для
# комментария означало бы хеширование всего текста — формально замена, по сути
# уничтожение данных. Персональные данные внутри закрывает слой подстановки.
FREE_TEXT_TYPES = {"text", "mediumtext", "longtext", "tinytext", "json"}

# ДВОИЧНЫЕ — правило myanon им тоже не назначается, но по другой причине:
# хеш от фотографии это не замена, а порча, и осматривать их детектором нечего.
# Найдено на sakila: `staff.picture` объявлен `blob` в официальном
# дистрибутиве 1.5 и `mediumblob` в распространённом зеркале 0.8, а прежний
# единый перечень знал только `blob`. Сопоставление точное (`тип in ...`,
# db_schema отдаёт голое имя типа в нижнем регистре), поэтому `mediumblob`
# мимо перечня проходил — и колонка с фотографией попадала и к модели,
# и в кандидаты на texthash.
BINARY_TYPES = {"blob", "tinyblob", "mediumblob", "longblob", "binary", "varbinary"}

# Колонки, которым правило myanon не назначается никогда, — объединение обоих.
# Этим перечнем пользуется сканер; детектор берёт только FREE_TEXT_TYPES.
NO_RULE_TYPES = FREE_TEXT_TYPES | BINARY_TYPES

# Значения короче этого порога не заменяются: подстановка идёт по всему
# тексту дампа, и на коротких строках она цепляла бы куски слов. Проверяющий
# пользуется тем же порогом — иначе он требовал бы замен, которых по
# построению нет. Лежит здесь, а не в text_substitute: импортировать порог
# из проверяемого модуля значило бы вернуть ту самую связь, которую
# развязка и убирала.
MIN_VALUE_LEN = 5

COLUMNS = {
    "customers": ["full_name", "email", "phone", "inn", "address"],
    "employees": ["full_name", "snils", "email"],
}


def _самопроверка():
    """Перечни не пересекаются, двоичные не попадают под осмотр детектором."""
    assert not (FREE_TEXT_TYPES & BINARY_TYPES), "тип не может быть и текстом, и двоичным"
    assert NO_RULE_TYPES == FREE_TEXT_TYPES | BINARY_TYPES
    # Именно этот тип из sakila и был пропущен прежним единым перечнем.
    assert "mediumblob" in NO_RULE_TYPES, "правило myanon не должно назначаться на mediumblob"
    assert "mediumblob" not in FREE_TEXT_TYPES, "двоичную колонку детектору не показывают"
    assert "text" in FREE_TEXT_TYPES and "text" in NO_RULE_TYPES
    print("pii_columns: самопроверка пройдена")


if __name__ == "__main__":
    _самопроверка()
