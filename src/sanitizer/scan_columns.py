#!/usr/bin/env python3
"""
Сканер колонок: модель смотрит на образцы значений и говорит, где персональные
данные. Первый шаг цикла автонастройки.

РАЗДЕЛЕНИЕ ОТВЕТСТВЕННОСТИ, и оно здесь главное.

Модель НЕ настраивает myanon. Она возвращает типизированный список находок —
таблица, колонка, вид данных. Конфиг из него собирает детерминированный код
(`config_builder.py`). Вывод модели не становится исполняемым: она не может ни
удалить существующее правило, ни сломать синтаксис, ни предложить действие,
которого нет в белом списке.

Модель спрашивается НЕ обо всём. Телефон, ИНН, СНИЛС и почту уже находит
`pii_patterns` по формату с проверкой контрольных сумм — там полнота доказуема
арифметикой. Отдавать эти колонки модели значит менять доказуемое на
вероятное. Сканер ищет то, чего формат не берёт: имена, адреса, свободный текст.

Ключевые колонки не показываются модели вовсе и отбрасываются повторно после
её ответа. Хеширование внешнего ключа разрушило бы связи между таблицами —
ровно то, что задание требует сохранить.
"""
import json
import os
import re
import sys
import urllib.request

from . import paths
from . import pii_patterns
from .db_schema import parse_schema
from .sql_parse import parse_inserts, unquote

ENDPOINT = os.environ.get("LLM_ENDPOINT", "http://localhost:12434/engines/v1/chat/completions")
MODEL = os.environ.get("LLM_MODEL", "ai/qwen3:14b-q4_K_M")
ОБРАЗЦОВ = 3

# Типы, которым правило myanon не назначается никогда, — общие данные,
# см. pii_columns: свободный текст плюс двоичные.
# Найдено первым же прогоном: модель предложила orders.comment трижды.
from .pii_columns import NO_RULE_TYPES as БЕЗ_ПРАВИЛА
from .pii_columns import FREE_TEXT_TYPES as СВОБОДНЫЙ_ТЕКСТ

# Белый список: вид находки -> как это обрабатывается. Чего здесь нет, в конфиг
# не попадёт, что бы модель ни ответила.
ВИДЫ = {
    "имя": "texthash",
    "адрес": "texthash",
    "почта": "emailhash",
}

ПРОМПТ = """/no_think Ниже колонки таблицы базы данных и по несколько образцов значений.

Назови колонки, которые содержат персональные данные конкретного человека:
его имя, его адрес проживания, его личную электронную почту.

НЕ называй:
- числовые идентификаторы и коды;
- телефоны, ИНН, СНИЛС — они обрабатываются отдельно, без тебя;
- город, регион, название отдела, должность, дату, сумму, название товара.

Ответь JSON-массивом объектов вида {{"колонка": "имя_колонки", "вид": "имя"}},
где вид — одно из: имя, адрес, почта. Если таких колонок нет, верни [].
Только JSON, без пояснений.

Таблица {таблица}:
{колонки}"""


def _вызов(prompt, timeout=180):
    body = json.dumps({
        "model": MODEL,
        "messages": [{"role": "user", "content": prompt}],
        "temperature": 0,
        "max_tokens": 500,
    }).encode()
    req = urllib.request.Request(ENDPOINT, data=body,
                                 headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        data = json.loads(r.read())
    text = data["choices"][0]["message"]["content"]
    return re.sub(r"<think>.*?</think>", "", text, flags=re.S).strip()


def образцы(rows, idx, n=ОБРАЗЦОВ):
    out = []
    for r in rows:
        v = unquote(r[idx])
        if v and v not in out:
            out.append(v)
        if len(out) >= n:
            break
    return out


def покрыто_форматом(значения):
    """Все ли непустые значения колонки распознаются форматным слоем."""
    непустые = [v for v in значения if v]
    if not непустые:
        return False
    return all(pii_patterns.find_values(v) for v in непустые)


def scan(dump_path):
    """
    Возвращает (находки, отчёт). Находка: {"таблица", "колонка", "вид"}.

    Отчёт объясняет, что было отброшено и почему — дифф конфига потом смотрит
    человек, и ему нужно видеть не только принятое.
    """
    схема = parse_schema(dump_path)
    данные = parse_inserts(dump_path)
    if not схема:
        raise ValueError("схема не разобрана — сканировать нечего")

    находки, отброшено = [], []

    for таблица, инфо in sorted(схема.items()):
        if таблица not in данные:
            continue
        cols, rows = данные[таблица]
        ключи = инфо["keys"]

        показать = []
        for имя, тип in инфо["columns"]:
            if имя in ключи:
                отброшено.append((таблица, имя, "ключевая колонка, модели не показана"))
                continue
            if тип in БЕЗ_ПРАВИЛА:
                почему = ("свободный текст; правило на всю колонку уничтожило бы "
                          "её содержимое, ПДн внутри закрывает слой подстановки"
                          if тип in СВОБОДНЫЙ_ТЕКСТ else
                          "двоичные данные; хеш от них — не замена, а порча")
                отброшено.append((таблица, имя, f"тип {тип} — {почему}"))
                continue
            if имя not in cols:
                continue
            обр = образцы(rows, cols.index(имя))
            if покрыто_форматом(обр):
                отброшено.append((таблица, имя, "покрыта форматным слоем, модели не показана"))
                continue
            показать.append((имя, обр))

        if not показать:
            continue

        текст = "\n".join(f"  {имя}: " + ", ".join(о) for имя, о in показать)
        сырое = _вызов(ПРОМПТ.format(таблица=таблица, колонки=текст))
        m = re.search(r"\[.*\]", сырое, re.S)
        if not m:
            raise ValueError(f"модель вернула не JSON для {таблица}: {сырое[:200]}")

        разрешённые = {имя for имя, _ in показать}
        for x in json.loads(m.group(0)):
            if not isinstance(x, dict):
                continue
            имя, вид = str(x.get("колонка", "")).strip(), str(x.get("вид", "")).strip()
            # Три детерминированных фильтра поверх ответа модели.
            if имя in ключи:
                отброшено.append((таблица, имя, "модель предложила ключевую колонку — отклонено"))
                continue
            if имя not in разрешённые:
                отброшено.append((таблица, имя, "колонки нет среди показанных — отклонено"))
                continue
            if вид not in ВИДЫ:
                отброшено.append((таблица, имя, f"вид «{вид}» вне белого списка — отклонено"))
                continue
            # Одна колонка — одно правило. Два правила на одну колонку myanon
            # не примет, а молча взятое первое скрыло бы противоречие в ответе
            # модели. Противоречие записывается в отчёт.
            прежний = next((f for f in находки
                            if f["таблица"] == таблица and f["колонка"] == имя), None)
            if прежний:
                if прежний["вид"] != вид:
                    отброшено.append((таблица, имя,
                                      f"модель назвала два разных вида: «{прежний['вид']}» "
                                      f"и «{вид}» — оставлен первый"))
                continue
            находки.append({"таблица": таблица, "колонка": имя, "вид": вид})

    return находки, отброшено


def main(dump_path, out="scan_report.json"):
    находки, отброшено = scan(dump_path)

    print(f"\nНайдено колонок с персональными данными: {len(находки)}")
    for f in находки:
        print(f"  {f['таблица']}.{f['колонка']}  ->  {f['вид']}")
    print(f"\nОтброшено детерминированными фильтрами: {len(отброшено)}")
    for t, c, why in отброшено:
        print(f"  {t}.{c}: {why}")

    with open(out, "w", encoding="utf-8") as fh:
        json.dump({"находки": находки, "отброшено": отброшено}, fh,
                  ensure_ascii=False, indent=1)
    print(f"\nОтчёт: {out}")

    # Пустой результат — это отказ, а не успех: сломанная модель и чистая база
    # дают один и тот же сигнал (красный флаг 2.17).
    if not находки:
        print("ОТКАЗ: не найдено ни одной колонки. Либо база уже чистая, либо "
              "сканер не работает — по этому выводу отличить нельзя.")
        return 1
    return 0


if __name__ == "__main__":
    # Второй аргумент — куда положить отчёт. Раньше он молча игнорировался,
    # и отчёт всегда падал в текущий каталог: найдено прогоном на sakila,
    # когда отчёт по чужой базе лёг в корень репозитория.
    аргументы = sys.argv[1:3] or [paths.данные("demo_dump.sql")]
    sys.exit(main(*аргументы))
